export function getNafisGradeById(gradeId: string): NafisGradeDefinition | undefined {
  return NAFIS_GRADES.find((g) => g.id === gradeId);
}

export function getNafisSubjectsForGrade(_gradeId: string): NafisSubjectDefinition[] {
  return NAFIS_SUBJECTS;
}

export function getNafisSubjectById(subjectId: string): NafisSubjectDefinition | undefined {
  return NAFIS_SUBJECTS.find((s) => s.id === subjectId);
}

export function buildNafisBankKey(gradeId: string, subjectId: string): string {
  return `${gradeId}_${subjectId}`;
}

export function isNafisBankKey(bankKey: string): boolean {
  return bankKey.startsWith('nafis_g');
}

export function parseNafisBankKey(
  bankKey: string
): { grade: NafisGradeDefinition; subject: NafisSubjectDefinition } | null {
  for (const grade of NAFIS_GRADES) {
    const prefix = `${grade.id}_`;
    if (bankKey.startsWith(prefix)) {
      const subjectId = bankKey.slice(prefix.length);
      const subject = getNafisSubjectById(subjectId);
      if (subject) {
        return { grade, subject };
      }
    }
  }
  return null;
}

