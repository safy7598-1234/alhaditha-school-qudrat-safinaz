const BUILTIN_NAFIS_COMPREHENSIVE_CACHE: Record<string, Question[]> = {
  nafis_g3: buildGrade3Questions(),
  nafis_g6: buildGrade6Questions(),
  nafis_g9: buildGrade9Questions()
};

export function getDefaultNafisQuestions(gradeId: string): Question[] {
  return BUILTIN_NAFIS_COMPREHENSIVE_CACHE[gradeId] || [];
}

export function buildDefaultNafisBankEntry(gradeId: string): SubjectBankEntry | null {
  const grade = getNafisGradeById(gradeId);
  if (!grade) return null;
  const questions = getDefaultNafisQuestions(gradeId);
  const bankKey = buildNafisBankKey(grade.id, 'comprehensive');
  return {
    bankKey,
    gradeId: grade.id,
    subjectId: 'comprehensive',
    title: `اختبار نافس التجريبي الشامل — ${grade.title}`,
    sourceFilename: `نموذج_نافس_${grade.shortTitle.replace(/\s+/g, '_')}.json`,
    durationMinutes: NAFIS_DURATION_MINUTES,
    questions,
    updatedAt: '2026-01-01T00:00:00.000Z'
  };
}

/**
 * Resolves the effective NAFIS bank for a grade & subject:
 * - If a supervisor saved or cleared an entry in `subjectBanks[bankKey]`, respects it (returns null if cleared to 0 questions).
 * - Otherwise, for `comprehensive`, returns the built-in 40-question (3rd Elem) or 70-question (6th Elem / 3rd Middle) 135-minute simulation bank.
 * - For individual subject banks (`reading`, `math`, `science`), returns null until a supervisor uploads questions.
 */
export function resolveEffectiveNafisBank(
  gradeId: string,
  subjectId: string,
  subjectBanks: SubjectBanksMap
): { bank: SubjectBankEntry | null; isCustomSupervisorBank: boolean } {
  const grade = getNafisGradeById(gradeId);
  const subject = getNafisSubjectById(subjectId);
  if (!grade || !subject) {
    return { bank: null, isCustomSupervisorBank: false };
  }

  const bankKey = buildNafisBankKey(grade.id, subject.id);
  const stored = subjectBanks[bankKey];

  if (stored) {
    if (!Array.isArray(stored.questions) || stored.questions.length === 0) {
      return { bank: null, isCustomSupervisorBank: true };
    }
    return {
      bank: {
        ...stored,
        durationMinutes: stored.durationMinutes || NAFIS_DURATION_MINUTES
      },
      isCustomSupervisorBank: true
    };
  }

  if (subject.id === 'comprehensive') {
    return {
      bank: buildDefaultNafisBankEntry(grade.id),
      isCustomSupervisorBank: false
    };
  }

  return { bank: null, isCustomSupervisorBank: false };
}

/**
 * Prepares the exam session questions for a NAFIS grade, enforcing the official target question count
 * (40 questions for 3rd Elementary; 70 questions for 6th Elementary & 3rd Middle) when the bank has at least that many.
 */
export function prepareNafisExamQuestions(questions: Question[], gradeId: string): Question[] {
  const grade = getNafisGradeById(gradeId);
  if (!grade) return questions;
  if (questions.length > grade.targetQuestionCount) {
    return questions.slice(0, grade.targetQuestionCount);
  }
  return questions;
}
